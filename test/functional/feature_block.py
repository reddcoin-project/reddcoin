        # In PoS blocks, coinstake typically has ~2 sigops (P2PK output)
        # The spend tx output uses default script (OP_TRUE pattern = ~1 sigop)
        # For P2SH counting: P2SH sigops are from the redeem script (6 each)
        base_sigops = COINSTAKE_SIGOPS + 1  # approximate
        numTxes = (MAX_BLOCK_SIGOPS - base_sigops) // b39_sigops_per_output
        assert numTxes <= b39_p2sh_count, f"Need {numTxes} P2SH txs but only {b39_p2sh_count} available"
        self.log.info(f"  Need {numTxes} P2SH spend txs (base_sigops={base_sigops})")

        # Verify b40's spend tx UTXO
        spend_txid = format(spend_tx40.sha256, '064x')
        self.log.info(f"  b40 spend tx: {spend_txid[:16]}... vout[0] check={node.gettxout(spend_txid, 0) is not None}")
        # Check if coinstake in b40 conflicts with any b39 P2SH output
        cs = b40.vtx[1]
        cs.rehash()
        cs_vin = cs.vin[0].prevout
        cs_txid = format(cs_vin.hash, '064x')
        self.log.info(f"  b40 coinstake input: {cs_txid[:16]}...:{cs_vin.n}")
        for check_idx in range(b39_p2sh_start, min(b39_p2sh_start + 5, len(b39.vtx))):
            b39.vtx[check_idx].rehash()
            b39_txid = format(b39.vtx[check_idx].sha256, '064x')
            if b39_txid == cs_txid:
                self.log.info(f"  CONFLICT: coinstake uses b39.vtx[{check_idx}] UTXO!")

        # Use fewer txs by spending MULTIPLE P2SH outputs per tx (10 each)
        # This reduces validation time while still testing the sigops limit
        # Use 1 P2SH input per tx for simplicity, but limit total txs to keep
        # validation fast. We still need total sigops > MAX_BLOCK_SIGOPS.
        # Instead of spending thousands of P2SH outputs, use the padding tx to
        # push past the limit. Spend just enough P2SH outputs to get close, then
        # add a big padding sigops tx.
        p2sh_per_tx = 1
        sigops_per_combined_tx = p2sh_per_tx * b39_sigops_per_output
        # Use only ~100 P2SH txs (fast validation), then pad with legacy sigops
        numTxes = min(100, b39_p2sh_count)
        p2sh_needed = numTxes * p2sh_per_tx
        assert p2sh_needed <= b39_p2sh_count, f"Need {p2sh_needed} but only {b39_p2sh_count}"

        lastOutpoint = COutPoint(spend_tx40.sha256, 0)
        new_txs = []
        p2sh_idx = 0
        mock_time_b40 = node.getblockheader(node.getbestblockhash())['time']
        for i in range(numTxes):
            tx = CTransaction()
            tx.nTime = mock_time_b40  # Sync with mocktime
            tx.vout.append(CTxOut(1, CScript([OP_TRUE])))
            tx.vin.append(CTxIn(lastOutpoint, b''))
            # Add multiple P2SH inputs to this tx
            for j in range(p2sh_per_tx):
                b39_tx = b39.vtx[b39_p2sh_start + p2sh_idx]
                b39_tx.rehash()
                tx.vin.append(CTxIn(COutPoint(b39_tx.sha256, 0), b''))
                p2sh_idx += 1
            # Sign all P2SH inputs (indices 1..p2sh_per_tx)
            for k in range(1, p2sh_per_tx + 1):
                (sighash, err) = LegacySignatureHash(redeem_script, tx, k, SIGHASH_ALL)
                sig = self.coinbase_key.sign_ecdsa(sighash) + bytes(bytearray([SIGHASH_ALL]))
                tx.vin[k].scriptSig = CScript([sig, redeem_script])
            tx.rehash()
            new_txs.append(tx)
            lastOutpoint = COutPoint(tx.sha256, 0)

        # Add padding tx to push sigops over the limit.
        # The b40 reject test uses MAX_BLOCK_SIGOPS sigops in the padding tx.
        # Combined with coinstake + P2SH sigops, this guarantees exceeding the limit.
        b40_sigops_to_fill = MAX_BLOCK_SIGOPS
        tx = CTransaction()
        tx.nTime = mock_time_b40
        tx.vin.append(CTxIn(lastOutpoint, b''))
        tx.vout.append(CTxOut(1, CScript([OP_CHECKSIG] * b40_sigops_to_fill)))
        tx.rehash()
        new_txs.append(tx)
        self.log.info(f"  Total txs for b40: {len(new_txs)} (each with {p2sh_per_tx} P2SH inputs), sigops_to_fill={b40_sigops_to_fill}")
        self.update_block(40, new_txs)
        self.log.info(f"  b40 size={len(b40.serialize())}, sending...")
        # Submit b40 via RPC — P2P hangs due to block validation time on large P2SH blocks.
        # submitblock processes synchronously and returns the rejection reason.
        prev_best = node.getbestblockhash()
        result = node.submitblock(b40.serialize().hex())
        self.log.info(f"  b40 submitblock result: {result}")
        assert result is not None, "b40 should have been rejected"
        assert_equal(node.getbestblockhash(), prev_best)
        self.reset_tip_to_node()

        # b41: same P2SH spending as b40, but one less sigop (should be accepted)
        # Rebuild from scratch since b40 was rejected (its tx chain doesn't exist on chain)
        self.log.info("Accept a block with the max number of P2SH sigops")
        advance_time_for_pos(node, seconds=3600)
        b41 = self.next_block(41, spend=out[18])
        spend_tx41 = b41.vtx[2]
