class FullBlockTest(BitcoinTestFramework):
    def set_test_params(self):
        self.num_nodes = 1
        self.setup_clean_chain = False  # Use 199-block cache for PoS
        self.extra_args = [['-acceptnonstdtxn=1', '-staking=0']]
        # ReddCoin: the large-reorg test generates ~2x LARGE_REORG_SIZE PoS blocks
        # one at a time via generatetoaddress. As the wallet accumulates coinstake
        # outputs the per-block coinstake search slows, and a single call can
        # exceed the default 30s RPC timeout. Raise the timeout as other heavy PoS
        # tests do.
        self.rpc_timeout = 480

    def skip_test_if_missing_module(self):
        self.skip_if_no_wallet()

    def run_test(self):
        node = self.nodes[0]  # convenience reference to the node

        self.bootstrap_p2p()  # Add one p2p connection to the node

        self.block_heights = {}
        self.coinbase_key = ECKey()
        self.coinbase_key.generate()
        self.coinbase_pubkey = self.coinbase_key.get_pubkey().get_bytes()
        self.coinbase_address = key_to_p2pkh(self.coinbase_pubkey)
        self.tip = None
        self.blocks = {}
        self._invalidated = []
        self._node_generated_blocks = set()  # Track blocks generated by node (skip P2P)
        self.spendable_outputs = []

        # Initialize from cache
        tip_hash = node.getbestblockhash()
        tip_height = node.getblockcount()
        self.block_heights[int(tip_hash, 16)] = tip_height

        NUM_OUTPUTS_TO_COLLECT = 40
        self._setup_spendable_outputs(node, num_outputs=NUM_OUTPUTS_TO_COLLECT + 5)

        # collect spendable outputs now to avoid cluttering the code later on
        out = []
        for _ in range(NUM_OUTPUTS_TO_COLLECT):
            out.append(self.get_spendable_output())

        # PoS: coinbase is empty, BIP30 duplicate coinbase check is skipped for PoS
        duplicate_tx = None

        # Start by building a couple of blocks on top (which output is spent is
        # in parentheses):
        #     ... cache -> b1 (0) -> b2 (1)
        b1 = self.next_block(1, spend=out[0])
        self.send_blocks([b1])

        b2 = self.next_block(2, spend=out[1])
        self.send_blocks([b2])

        # Select a txn with an output eligible for spending. This won't actually be spent,
        # since we're testing submission of a series of blocks with invalid txns.
        attempt_spend_tx = out[2]

        # Submit blocks for rejection, each of which contains a single transaction
        # (aside from coinbase) which should be considered invalid.
        for TxTemplate in invalid_txs.iter_all_templates():
            template = TxTemplate(spend_tx=attempt_spend_tx)

            if template.valid_in_block:
                continue

            self.log.info(f"Reject block with invalid tx: {TxTemplate.__name__}")
            blockname = f"for_invalid.{TxTemplate.__name__}"
            badblock = self.next_block(blockname)
            badtx = template.get_tx()
            if TxTemplate != invalid_txs.InputMissing:
                self.sign_tx(badtx, attempt_spend_tx)
            badtx.rehash()
            badblock = self.update_block(blockname, [badtx])
            self.send_blocks(
                [badblock], success=False,
                reject_reason=(template.block_reject_reason or template.reject_reason),
                reconnect=True, timeout=2)

            self.move_tip(2)

        # Fork like this:
        #
        #     genesis -> b1 (0) -> b2 (1)
        #                      \-> b3 (1)
        #
        # Nothing should happen at this point. We saw b2 first so it takes priority.
        self.log.info("Don't reorg to a chain of the same length")
        self.move_tip(1)
        b3 = self.next_block(3, spend=out[1])
        # PoS fork block: spend tx may be at vtx[2] if included, or vtx[1] (coinstake) if not
        txout_b3 = b3.vtx[2] if len(b3.vtx) > 2 else b3.vtx[1]
        self.send_blocks([b3], False)

        # Now we add another block to make the alternative chain longer.
        #
        #     genesis -> b1 (0) -> b2 (1)
        #                      \-> b3 (1) -> b4 (2)
        self.log.info("Reorg to a longer chain")
        b4 = self.next_block(4, spend=out[2])
        self.send_blocks([b4])

        # ... and back to the first chain.
        #     genesis -> b1 (0) -> b2 (1) -> b5 (2) -> b6 (3)
        #                      \-> b3 (1) -> b4 (2)
        self.move_tip(2)
        b5 = self.next_block(5, spend=out[2])
        self.save_spendable_output()
        self.send_blocks([b5], False)

        self.log.info("Reorg back to the original chain")
        b6 = self.next_block(6, spend=out[3])
        self.send_blocks([b6], True)

        # Try to create a fork that double-spends
        #     genesis -> b1 (0) -> b2 (1) -> b5 (2) -> b6 (3)
        #                                          \-> b7 (2) -> b8 (4)
        #                      \-> b3 (1) -> b4 (2)
        self.log.info("Reject a chain with a double spend, even if it is longer")
        self.move_tip(5)
        b7 = self.next_block(7, spend=out[2])
        self.send_blocks([b7], False)

        b8 = self.next_block(8, spend=out[4])
        self.send_blocks([b8], False, reconnect=True)

        # Try to create a block that has too much fee
        #     genesis -> b1 (0) -> b2 (1) -> b5 (2) -> b6 (3)
        #                                                    \-> b9 (4)
        #                      \-> b3 (1) -> b4 (2)
        # PoS: coinbase reward check is 'bad-posv-amount' (coinstake reward too high)
        self.log.info("Reject a block where the staker creates too much coinstake reward")
        self.move_tip(6)
        b9 = self.next_block(9, spend=out[4], additional_coinbase_value=1)
        self.submit_and_reject(b9, 'bad-posv-amount')

        # PoS: Fork-chain reward tests (b10/b11, b12/b13/b14) require modifying
        # coinstake in node-generated blocks, which invalidates the PoS kernel.
        # Skip these and build the fork chain with valid blocks for chain continuity.
        #     ... -> b5 (2) -> b6 (3)
        #                  \-> b12 (3) -> b13 (4)
        self.log.info("Reject a chain where the miner creates too much coinbase reward, even if the chain is longer")
        self.log.info("  (PoS: skipped — cannot modify coinstake in node-generated fork blocks)")
        self.log.info("Reject a chain where the miner creates too much coinbase reward, even if the chain is longer (on a forked chain)")
        self.log.info("  (PoS: skipped — building fork chain for continuity)")
        self.move_tip(5)
        b12 = self.next_block(12, spend=out[3])
        self.save_spendable_output()
        b13 = self.next_block(13, spend=out[4])
        self.save_spendable_output()
        # b12/b13 fork is same length as main chain (b6), so no reorg
        self.send_blocks([b12, b13], False)

        # Add a block with MAX_BLOCK_SIGOPS and one with one more sigop
        #     genesis -> b1 (0) -> b2 (1) -> b5 (2) -> b6  (3)
        #                                          \-> b12 (3) -> b13 (4) -> b15 (5) -> b16 (6)
        #                      \-> b3 (1) -> b4 (2)
        # PoS: coinstake adds 1 sigop (OP_CHECKSIG in P2PK output), so adjust limits
        COINSTAKE_SIGOPS = 2  # P2PK outputs in coinstake (may have multiple)
        self.log.info("Accept a block with lots of checksigs")
        lots_of_checksigs = CScript([OP_CHECKSIG] * (MAX_BLOCK_SIGOPS - 1 - COINSTAKE_SIGOPS))
        self.move_tip(13)
        b15 = self.next_block(15, spend=out[5], script=lots_of_checksigs)
        self.save_spendable_output()
        self.send_blocks([b15], True)

        self.log.info("Reject a block with too many checksigs")
        too_many_checksigs = CScript([OP_CHECKSIG] * (MAX_BLOCK_SIGOPS))  # guaranteed over limit
        b16 = self.next_block(16, spend=out[6], script=too_many_checksigs)
        self.log.info(f"  b16 sending, size={len(b16.serialize())}")
        self.submit_and_reject(b16, 'bad-blk-sigops')
        self.log.info("  b16 rejected, reconnected")
        self.reset_tip_to_node()
        self.log.info("  tip reset to node")

        # PoS: Skip re-org'd tx spend tests (b17, b18, b19)
        self.log.info("Reject a block with a spend from a re-org'ed out tx")
        self.log.info("  (PoS: skipped — fork blocks are node-generated)")
        self.log.info("Reject a block with a spend from a re-org'ed out tx (on a forked chain)")
        self.log.info("  (PoS: skipped — fork blocks are node-generated)")

        # PoS: Test spending immature coinstake output instead of immature coinbase.
        self.log.info("Reject a block spending an immature coinstake.")

        # Generate a block to get a fresh coinstake output
        # Need aggressive time advancement — wallet UTXOs may have been consumed
        advance_time_for_pos(node, seconds=3600)
        immature_hash = node.generate(1)[0]
        immature_block = self._get_block_from_node(immature_hash)
        immature_height = node.getblockcount()
        self.block_heights[immature_block.sha256] = immature_height
        self.blocks[20] = immature_block
        self.tip = immature_block

        # Get the coinstake output (vtx[1].vout[1] — first non-empty output)
        coinstake_tx = immature_block.vtx[1]
        coinstake_tx.rehash()
        # Create a spend of the immature coinstake output
        immature_spend = SpendableOutput(coinstake_tx, spend_vout=1)

        # Build a block that spends the immature coinstake
        b20 = self.next_block("b20_immature", spend=immature_spend)
        self.submit_and_reject(b20, 'bad-txns-premature-spend-of-coinbase')

        # Attempt to spend a coinbase at depth too low (on a fork this time)
        #     genesis -> b1 (0) -> b2 (1) -> b5 (2) -> b6  (3)
        #                                          \-> b12 (3) -> b13 (4) -> b15 (5)
        #                                                                \-> b21 (6) -> b22 (5)
        #                      \-> b3 (1) -> b4 (2)
        self.log.info("Reject a block spending an immature coinbase (on a forked chain)")
        self.move_tip(13)
        b21 = self.next_block(21, spend=out[6])
        self.send_blocks([b21], False)

        b22 = self.next_block(22, spend=out[5])
        self.submit_and_reject(b22, 'bad-txns-premature-spend-of-coinbase')

        # Create a block on either side of MAX_BLOCK_BASE_SIZE and make sure its accepted/rejected
        #     genesis -> b1 (0) -> b2 (1) -> b5 (2) -> b6  (3)
        #                                          \-> b12 (3) -> b13 (4) -> b15 (5) -> b23 (6)
        #                                                                           \-> b24 (6) -> b25 (7)
        #                      \-> b3 (1) -> b4 (2)
        # PoS: Block size tests — PoS blocks include coinstake + block signature,
        # adding ~100-200 bytes overhead. Adapt the max block size test to account for this.
        self.log.info("Accept a block of size MAX_BLOCK_BASE_SIZE")
        self.reset_tip_to_node()
        b23 = self.next_block(23, spend=out[6])
        spend_tx23 = b23.vtx[2]  # PoS: spend tx at vtx[2]
        spend_tx23.rehash()
        tx = CTransaction()
        # Calculate padding for max size, accounting for PoS overhead
        current_size = len(b23.serialize())
        script_length = MAX_BLOCK_BASE_SIZE - current_size - 69
        if script_length > 0:
            # PoS: block signature is variable-length DER (70-72 bytes).
            # First add a minimal padding tx, re-sign, measure the actual block size,
            # then compute the exact script length needed.
            pad_tx = CTransaction()
            pad_tx.vout.append(CTxOut(0, CScript([b'\x00'])))  # 1-byte placeholder
            pad_tx.vin.append(CTxIn(COutPoint(spend_tx23.sha256, 0)))
            b23 = self.update_block(23, [pad_tx])
            # Measure overhead: actual_size = block_without_script + 1 + tx_overhead
            overhead = len(b23.serialize()) - 1  # subtract the 1 placeholder byte
            exact_length = MAX_BLOCK_BASE_SIZE - overhead
            # Rebuild with exact script length
            while len(b23.vtx) > 3:
                b23.vtx.pop()
            pad_tx2 = CTransaction()
            pad_tx2.vout.append(CTxOut(0, CScript([b'\x00' * exact_length])))
            pad_tx2.vin.append(CTxIn(COutPoint(spend_tx23.sha256, 0)))
            b23 = self.update_block(23, [pad_tx2])
            # The re-signing might shift by 1-2 bytes, adjust
            while len(b23.serialize()) != MAX_BLOCK_BASE_SIZE:
                diff = len(b23.serialize()) - MAX_BLOCK_BASE_SIZE
                exact_length -= diff
                while len(b23.vtx) > 3:
                    b23.vtx.pop()
                pad_tx3 = CTransaction()
                pad_tx3.vout.append(CTxOut(0, CScript([b'\x00' * exact_length])))
                pad_tx3.vin.append(CTxIn(COutPoint(spend_tx23.sha256, 0)))
                b23 = self.update_block(23, [pad_tx3])
            assert_equal(len(b23.serialize()), MAX_BLOCK_BASE_SIZE)
            self.send_blocks([b23], True)
            self.save_spendable_output()
        else:
            self.log.info(f"  (PoS: base block already {current_size} bytes, skipping exact size test)")
            self.send_blocks([b23], True)
            self.save_spendable_output()

        self.log.info("Reject a block of size MAX_BLOCK_BASE_SIZE + 1")
        b24 = self.next_block(24, spend=out[7])
        spend_tx24 = b24.vtx[2]
        spend_tx24.rehash()
        current_size = len(b24.serialize())
        padding = MAX_BLOCK_BASE_SIZE - current_size - 69 + 1  # +1 to exceed limit
        if padding > 0:
            # PoS: block signature is variable-length DER (70-72 bytes).
            # Use same convergence approach as b23: add minimal pad, measure, adjust.
            target_size = MAX_BLOCK_BASE_SIZE + 1
            pad_tx = CTransaction()
            pad_tx.vout.append(CTxOut(0, CScript([b'\x00'])))
            pad_tx.vin.append(CTxIn(COutPoint(spend_tx24.sha256, 0)))
            b24 = self.update_block(24, [pad_tx])
            overhead = len(b24.serialize()) - 1
            exact_length = target_size - overhead
            while len(b24.vtx) > 3:
                b24.vtx.pop()
            pad_tx2 = CTransaction()
            pad_tx2.vout.append(CTxOut(0, CScript([b'\x00' * exact_length])))
            pad_tx2.vin.append(CTxIn(COutPoint(spend_tx24.sha256, 0)))
            b24 = self.update_block(24, [pad_tx2])
            while len(b24.serialize()) != target_size:
                diff = len(b24.serialize()) - target_size
                exact_length -= diff
                while len(b24.vtx) > 3:
                    b24.vtx.pop()
                pad_tx3 = CTransaction()
                pad_tx3.vout.append(CTxOut(0, CScript([b'\x00' * exact_length])))
                pad_tx3.vin.append(CTxIn(COutPoint(spend_tx24.sha256, 0)))
                b24 = self.update_block(24, [pad_tx3])
        assert_equal(len(b24.serialize()), MAX_BLOCK_BASE_SIZE + 1)
        self.submit_and_reject(b24, 'bad-blk-length')
        self.reset_tip_to_node()

        # Coinbase input script size tests — build on current node tip
        self.log.info("Reject a block with coinbase input script size out of range")
        self.reset_tip_to_node()
        b26 = self.next_block(26, spend=out[8])
        b26.vtx[0].vin[0].scriptSig = b'\x00'
        b26.vtx[0].rehash()
        b26 = self.update_block(26, [])
        self.submit_and_reject(b26, 'bad-cb-length')
        self.reset_tip_to_node()

        # Now try a too-large-coinbase script
        b28 = self.next_block(28, spend=out[9])
        b28.vtx[0].vin[0].scriptSig = b'\x00' * 101
        b28.vtx[0].rehash()
        b28 = self.update_block(28, [])
        self.submit_and_reject(b28, 'bad-cb-length')
        self.reset_tip_to_node()

        # b30 has a max-sized coinbase scriptSig.
        b30 = self.next_block(30)
        b30.vtx[0].vin[0].scriptSig = b'\x00' * 100
        b30.vtx[0].rehash()
        b30 = self.update_block(30, [])
        self.send_blocks([b30], True)
        self.save_spendable_output()

        # b31 - b36: sigops of OP_CHECKMULTISIG / OP_CHECKMULTISIGVERIFY / OP_CHECKSIGVERIFY
        # PoS coinstake adds 1 sigop — adjust counts accordingly
        # Available sigops for the spend tx script = MAX - 1 - coinstake_sigops
        # (the -1 ensures we're at the limit, not over)
        AVAILABLE_SIGOPS = MAX_BLOCK_SIGOPS - 1 - COINSTAKE_SIGOPS  # 19997

        self.log.info("Accept a block with the max number of OP_CHECKMULTISIG sigops")
        # Each CHECKMULTISIG = 20 sigops, fill remainder with CHECKSIG (1 each)
        n_multi = AVAILABLE_SIGOPS // 20  # 999 multisigs = 19980
        n_single = AVAILABLE_SIGOPS - (n_multi * 20)  # 17 checksigs
        lots_of_multisigs = CScript([OP_CHECKMULTISIG] * n_multi + [OP_CHECKSIG] * n_single)
        b31 = self.next_block(31, spend=out[10], script=lots_of_multisigs)
        self.send_blocks([b31], True)
        self.save_spendable_output()

        self.log.info("Reject a block with too many OP_CHECKMULTISIG sigops")
        # One more multisig than allowed
        n_multi_bad = (AVAILABLE_SIGOPS + 1) // 20 + 1
        too_many_multisigs = CScript([OP_CHECKMULTISIG] * n_multi_bad)
        b32 = self.next_block(32, spend=out[11], script=too_many_multisigs)
        self.submit_and_reject(b32, 'bad-blk-sigops')
        self.reset_tip_to_node()

        # CHECKMULTISIGVERIFY
        self.log.info("Accept a block with the max number of OP_CHECKMULTISIGVERIFY sigops")
        lots_of_multisigs = CScript([OP_CHECKMULTISIGVERIFY] * n_multi + [OP_CHECKSIG] * n_single)
        b33 = self.next_block(33, spend=out[12], script=lots_of_multisigs)
        self.send_blocks([b33], True)
        self.save_spendable_output()

        self.log.info("Reject a block with too many OP_CHECKMULTISIGVERIFY sigops")
        too_many_multisigs = CScript([OP_CHECKMULTISIGVERIFY] * n_multi_bad)
        b34 = self.next_block(34, spend=out[13], script=too_many_multisigs)
        self.submit_and_reject(b34, 'bad-blk-sigops')
        self.reset_tip_to_node()

        # CHECKSIGVERIFY
        self.log.info("Accept a block with the max number of OP_CHECKSIGVERIFY sigops")
        lots_of_checksigs = CScript([OP_CHECKSIGVERIFY] * AVAILABLE_SIGOPS)
        b35 = self.next_block(35, spend=out[14], script=lots_of_checksigs)
        self.send_blocks([b35], True)
        self.save_spendable_output()

        self.log.info("Reject a block with too many OP_CHECKSIGVERIFY sigops")
        too_many_checksigs = CScript([OP_CHECKSIGVERIFY] * (AVAILABLE_SIGOPS + 2))  # +2 to exceed MAX with coinstake
        b36 = self.next_block(36, spend=out[15], script=too_many_checksigs)
        self.submit_and_reject(b36, 'bad-blk-sigops')
        self.log.info("  b36 rejected, resetting tip...")
        self.reset_tip_to_node()
        self.log.info(f"  tip reset, node at height {node.getblockcount()}")

        # Check spending of a transaction in a block which failed to connect
        # b37 creates a block with a double-spend (spend + spend-again of same output)
        self.log.info("Reject a block spending transaction from a block which failed to connect")
        advance_time_for_pos(node, seconds=3600)  # Ensure staking UTXOs have enough age
        self.log.info("  Building b37...")
        b37 = self.next_block(37, spend=out[16])
        txout_b37 = b37.vtx[2]  # PoS: spend tx at vtx[2] (after coinbase + coinstake)
        tx = self.create_and_sign_transaction(out[16], 0)  # double-spend same output
        b37 = self.update_block(37, [tx])
        self.submit_and_reject(b37, 'bad-txns-inputs-missingorspent')
        self.reset_tip_to_node()

        # attempt to spend b37's first non-coinbase tx, at which point b37 was still considered valid
        b38 = self.next_block(38, spend=txout_b37)
        self.submit_and_reject(b38, 'bad-txns-inputs-missingorspent')
        self.reset_tip_to_node()

        # Check P2SH SigOp counting
        #
        # b39 - create some P2SH outputs that will require 6 sigops to spend
        self.log.info("Check P2SH SIGOPS are correctly counted")
        b39 = self.next_block(39)
        b39_outputs = 0
        b39_sigops_per_output = 6

        # Build the redeem script, hash it, use hash to create the p2sh script
        redeem_script = CScript([self.coinbase_pubkey] + [OP_2DUP, OP_CHECKSIGVERIFY] * 5 + [OP_CHECKSIG])
        p2sh_script = script_to_p2sh_script(redeem_script)

        # Create a transaction that spends one satoshi to the p2sh_script, the rest to OP_TRUE
        spend = out[17]
        spend_n = getattr(spend, '_spend_vout', 0)
        tx = self.create_tx(spend, spend_n, 1, p2sh_script)
        tx.nTime = node.getblockheader(node.getbestblockhash())['time']  # Sync with mocktime
        tx.vout.append(CTxOut(spend.vout[spend_n].nValue - 1, CScript([OP_TRUE])))
        self.sign_tx(tx, spend)
        tx.rehash()
        b39 = self.update_block(39, [tx])
        b39_outputs += 1

        # Until block is full, add tx's with 1 satoshi to p2sh_script, the rest to OP_TRUE
        tx_new = None
        tx_last = tx
        total_size = len(b39.serialize())
        mock_time = node.getblockheader(node.getbestblockhash())['time']
        while(total_size < MAX_BLOCK_BASE_SIZE):
            tx_new = self.create_tx(tx_last, 1, 1, p2sh_script)
            tx_new.nTime = mock_time  # Sync with mocktime
            tx_new.vout.append(CTxOut(tx_last.vout[1].nValue - 1, CScript([OP_TRUE])))
            tx_new.rehash()
            total_size += len(tx_new.serialize())
            if total_size >= MAX_BLOCK_BASE_SIZE:
                break
            b39.vtx.append(tx_new)  # add tx to block
            tx_last = tx_new
            b39_outputs += 1

