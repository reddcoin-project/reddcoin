        # compact size encoding of the number of transactions in the block.
        # Make sure we didn't accidentally make too big a block. Note that the
        # size of the block has non-determinism due to the ECDSA signature in
        # the first transaction.
        while (len(b39.serialize()) >= MAX_BLOCK_BASE_SIZE):
            del b39.vtx[-1]

        b39 = self.update_block(39, [])
        self.send_blocks([b39], True)
        self.save_spendable_output()

        # Test sigops in P2SH redeem scripts
        #
        # b40 creates 3333 tx's spending the 6-sigop P2SH outputs from b39 for a total of 19998 sigops.
        # The first tx has one sigop and then at the end we add 2 more to put us just over the max.
        #
        # b41 does the same, less one, so it has the maximum sigops permitted.
        #
        self.log.info("Reject a block with too many P2SH sigops")
        advance_time_for_pos(node, seconds=3600)
        b40 = self.next_block(40, spend=out[18])
        # PoS: spend tx at vtx[2]
        spend_tx40 = b40.vtx[2]
        spend_tx40.rehash()

        # Verify b39's P2SH outputs exist in the UTXO set
        b39_p2sh_start = 2  # PoS: first P2SH tx at vtx[2] (after coinbase + coinstake)
        b39_p2sh_count = len(b39.vtx) - b39_p2sh_start
        self.log.info(f"  b39 has {b39_p2sh_count} P2SH txs (vtx[{b39_p2sh_start}]..vtx[{len(b39.vtx)-1}])")

