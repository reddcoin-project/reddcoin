        for check_idx in [b39_p2sh_start, b39_p2sh_start + 1, b39_p2sh_start + 2]:
            if check_idx < len(b39.vtx):
                check_tx = b39.vtx[check_idx]
                check_tx.rehash()
                txid = format(check_tx.sha256, '064x')
                utxo = node.gettxout(txid, 0)
                self.log.info(f"  b39.vtx[{check_idx}] sha256={txid[:16]}... vout[0] exists={utxo is not None}")

