        # base_legacy = COINSTAKE_SIGOPS + 1 (spend tx) = 3
        # p2sh_sigops = numTxes × 6 = 600
        # (3 + X) × 4 + 600 × 4 ≤ 80000 → X ≤ (80000/4 - 600) - 3 = 19397
